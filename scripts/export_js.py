"""Generate docs/data.js (rules, fallback replies, examples) from the Python source of truth."""
import json
from pathlib import Path
from second_look.rules import RULES
from second_look.model import FALLBACK_REPLY

root = Path(__file__).resolve().parent.parent
rules = [{"id": r.id, "severity": r.severity, "title": r.title.replace("*", ""), "why": r.why, "patterns": list(r.patterns)} for r in RULES]
examples = [{"name": p.stem, "text": p.read_text().strip()} for p in sorted((root / "examples").glob("*.txt"))]
js = ("// Generated by scripts/export_js.py from second_look/rules.py. Do not edit by hand.\n"
      f"const RULES = {json.dumps(rules, indent=1)};\nconst FALLBACK_REPLY = {json.dumps(FALLBACK_REPLY, indent=1)};\n"
      f"const EXAMPLES = {json.dumps(examples, indent=1)};\n"
      "if (typeof module !== 'undefined') module.exports = { RULES, FALLBACK_REPLY, EXAMPLES };\n")
(root / "docs" / "data.js").write_text(js)
print("wrote docs/data.js", len(rules), "rules", len(examples), "examples")
